export type BoxScoreRow = {
  playerId: string;
  pts: number;
  reb: number;
  ast: number;
  stl: number;
  blk: number;
  fgMade: number;
  fgAttempted: number;
  fgPct: number | null;
};

/**
 * Aggregates `game_events_log` into a per-player box score for one game
 * session. event_type is free-text; this recognizes the shot/stat vocabulary
 * a live-game recorder would use ('fg2'/'fg3'/'ft' + is_success for makes,
 * 'reb'/'ast'/'stl'/'blk' as counting events). No screen in this app writes
 * that log yet, so today this will almost always resolve to an empty list —
 * that's a real "no data recorded" result, not a bug.
 */
export async function getLastGameBoxScore(teamId: string): Promise<{ event: CoachEvent | null; rows: BoxScoreRow[]; score: { home: number; away: number } | null }> {
  const [lastGame] = await getRecentGames(teamId, 1);
  if (!lastGame) return { event: null, rows: [], score: null };

  const { data: sessionRows } = await supabase
    .from('games_live_session')
    .select('id, home_score, away_score')
    .eq('event_id', lastGame.id)
    .limit(1);
  const session = sessionRows?.[0];
  if (!session) return { event: lastGame, rows: [], score: null };

  const { data: logRows } = await supabase
    .from('game_events_log')
    .select('player_id, event_type, is_success')
    .eq('game_session_id', session.id);

  const byPlayer = new Map<string, BoxScoreRow>();
  const get = (playerId: string) => {
    let row = byPlayer.get(playerId);
    if (!row) {
      row = { playerId, pts: 0, reb: 0, ast: 0, stl: 0, blk: 0, fgMade: 0, fgAttempted: 0, fgPct: null };
      byPlayer.set(playerId, row);
    }
    return row;
  };

  for (const log of logRows ?? []) {
    const row = get(log.player_id as string);
    const type = log.event_type as string;
    const success = Boolean(log.is_success);
    if (type === 'fg2' || type === 'fg3') {
      row.fgAttempted += 1;
      if (success) {
        row.fgMade += 1;
        row.pts += type === 'fg3' ? 3 : 2;
      }
    } else if (type === 'ft' && success) {
      row.pts += 1;
    } else if (type === 'reb') row.reb += 1;
    else if (type === 'ast') row.ast += 1;
    else if (type === 'stl') row.stl += 1;
    else if (type === 'blk') row.blk += 1;
  }

  for (const row of byPlayer.values()) {
    row.fgPct = row.fgAttempted > 0 ? Math.round((row.fgMade / row.fgAttempted) * 100) : null;
  }

  return { event: lastGame, rows: [...byPlayer.values()], score: { home: session.home_score as number, away: session.away_score as number } };
}

export type GameLogEntry = { event: CoachEvent; row: BoxScoreRow };

/** One player's box score for each of their last `limit` completed games (most recent first). */
export async function getPlayerGameLog(teamId: string, playerId: string, limit = 5): Promise<GameLogEntry[]> {
  const games = await getRecentGames(teamId, limit);
  if (!games.length) return [];

  const eventIds = games.map((g) => g.id);
  const { data: sessionRows } = await supabase.from('games_live_session').select('id, event_id').in('event_id', eventIds);
  const sessions = sessionRows ?? [];
  if (!sessions.length) return [];

  const sessionByEvent = new Map(sessions.map((s) => [s.event_id as string, s.id as string]));
  const { data: logRows } = await supabase
    .from('game_events_log')
    .select('game_session_id, event_type, is_success')
    .eq('player_id', playerId)
    .in(
      'game_session_id',
      sessions.map((s) => s.id as string)
    );

  const bySession = new Map<string, BoxScoreRow>();
  const get = (sessionId: string) => {
    let row = bySession.get(sessionId);
    if (!row) {
      row = { playerId, pts: 0, reb: 0, ast: 0, stl: 0, blk: 0, fgMade: 0, fgAttempted: 0, fgPct: null };
      bySession.set(sessionId, row);
    }
    return row;
  };
  for (const log of logRows ?? []) {
    const row = get(log.game_session_id as string);
    const type = log.event_type as string;
    const success = Boolean(log.is_success);
    if (type === 'fg2' || type === 'fg3') {
      row.fgAttempted += 1;
      if (success) {
        row.fgMade += 1;
        row.pts += type === 'fg3' ? 3 : 2;
      }
    } else if (type === 'ft' && success) row.pts += 1;
    else if (type === 'reb') row.reb += 1;
    else if (type === 'ast') row.ast += 1;
    else if (type === 'stl') row.stl += 1;
    else if (type === 'blk') row.blk += 1;
  }
  for (const row of bySession.values()) row.fgPct = row.fgAttempted > 0 ? Math.round((row.fgMade / row.fgAttempted) * 100) : null;

  const out: GameLogEntry[] = [];
  for (const g of games) {
    const sessionId = sessionByEvent.get(g.id);
    if (!sessionId) continue;
    const row = bySession.get(sessionId);
    if (row && (row.fgAttempted > 0 || row.pts > 0 || row.reb > 0 || row.ast > 0 || row.stl > 0 || row.blk > 0)) {
      out.push({ event: g, row });
    }
  }
  return out;
}

export type TrendPoint = { eventId: string; label: string; fgPct: number | null };

/** Shooting % per game, most recent N completed games, for one player. */
export async function getShootingTrend(teamId: string, playerId: string, limit = 6): Promise<TrendPoint[]> {
  const games = await getRecentGames(teamId, limit);
  if (!games.length) return [];

  const eventIds = games.map((g) => g.id);
  const { data: sessionRows } = await supabase.from('games_live_session').select('id, event_id').in('event_id', eventIds);
  const sessionByEvent = new Map((sessionRows ?? []).map((s) => [s.event_id as string, s.id as string]));
  const sessionIds = [...sessionByEvent.values()];
  if (!sessionIds.length) return games.map((g) => ({ eventId: g.id, label: formatShortDate(g.startsAt), fgPct: null })).reverse();

  const { data: logRows } = await supabase
    .from('game_events_log')
    .select('game_session_id, player_id, event_type, is_success')
    .eq('player_id', playerId)
    .in('game_session_id', sessionIds)
    .in('event_type', ['fg2', 'fg3']);

  const bySession = new Map<string, { made: number; attempted: number }>();
  for (const log of logRows ?? []) {
    const key = log.game_session_id as string;
    const bucket = bySession.get(key) ?? { made: 0, attempted: 0 };
    bucket.attempted += 1;
    if (log.is_success) bucket.made += 1;
    bySession.set(key, bucket);
  }

  return games
    .map((g) => {
      const sessionId = sessionByEvent.get(g.id);
      const bucket = sessionId ? bySession.get(sessionId) : undefined;
      const fgPct = bucket && bucket.attempted > 0 ? Math.round((bucket.made / bucket.attempted) * 100) : null;
      return { eventId: g.id, label: formatShortDate(g.startsAt), fgPct };
    })
    .reverse();
}

function formatShortDate(iso: string): string {
  return new Date(iso).toLocaleDateString('en-US', { weekday: 'short' });
}

