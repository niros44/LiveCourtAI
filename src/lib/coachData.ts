export async function getPlaybooks(teamId: string): Promise<Playbook[]> {
  if (DESIGN_PREVIEW) return fxPlaybooks;
  const { data, error } = await supabase
    .from('playbooks')
    .select('id, team_id, title, category, plays ( id, playbook_id, title, canvas_data, notes, display_order )')
    .eq('team_id', teamId)
    .eq('is_active', true)
    .order('created_at', { ascending: false });
  if (error) throw error;

  return (data ?? []).map((pb) => ({
    id: pb.id as string,
    teamId: (pb.team_id as string | null) ?? null,
    title: pb.title as string,
    category: (pb.category as PlaybookCategory | null) ?? null,
    plays: ((pb as any).plays ?? [])
      .filter((p: any) => p.is_active !== false)
      .sort((a: any, b: any) => (a.display_order ?? 0) - (b.display_order ?? 0))
      .map((p: any) => ({
        id: p.id as string,
        playbookId: p.playbook_id as string,
        title: p.title as string,
        canvasData: (p.canvas_data as CourtDiagram) ?? { markers: [] },
        notes: (p.notes as string | null) ?? null,
        displayOrder: (p.display_order as number) ?? 0,
      })),
  }));
}

export async function createPlaybook(input: { authorId: string; clubId: string; teamId: string; title: string; category: PlaybookCategory }): Promise<string> {
  const { data, error } = await supabase
    .from('playbooks')
    .insert({ author_id: input.authorId, club_id: input.clubId, team_id: input.teamId, title: input.title, category: input.category })
    .select('id')
    .single();
  if (error) throw error;
  return data.id as string;
}

export async function savePlay(input: { playbookId: string; title: string; canvasData: CourtDiagram; displayOrder: number }): Promise<void> {
  const { error } = await supabase.from('plays').insert({
    playbook_id: input.playbookId,
    title: input.title,
    canvas_data: input.canvasData,
    display_order: input.displayOrder,
  });
  if (error) throw error;
}

