/** Every active roster row for `teamIds`, one entry per player per team. */
export async function getRosters(teamIds: string[]): Promise<RosterPlayer[]> {
  if (!teamIds.length) return [];
  const { data, error } = await supabase
    .from('team_members')
    .select('team_id, jersey_number, court_position, players ( id, first_name, last_name )')
    .in('team_id', teamIds)
    .eq('is_active', true);
  if (error) throw error;

  return (data ?? []).map((r) => {
    const p = (r as any).players as { id: string; first_name: string | null; last_name: string | null } | null;
    const first = p?.first_name ?? '';
    const last = p?.last_name ?? '';
    const name = [first, last].filter(Boolean).join(' ') || 'Player';
    return {
      id: p?.id as string,
      teamId: r.team_id as string,
      jersey: (r.jersey_number as number | null) ?? null,
      name,
      firstName: first || name,
      initials: `${first[0] ?? ''}${last[0] ?? ''}`.toUpperCase() || '?',
      position: (r.court_position as string | null) ?? null,
    };
  });
}

