export type CoachTeam = {
  id: string; // teams.id
  clubId: string;
  name: string;
  clubName: string;
  label: string; // "{club} · {team}"
  color: string;
};

export async function getMyTeams(personId: string): Promise<CoachTeam[]> {
  const { data, error } = await supabase
    .from('team_coaches')
    .select('team_id, teams ( id, name, club_id, clubs ( name ) )')
    .eq('user_id', personId)
    .eq('is_active', true);
  if (error) throw error;

  const rows = data ?? [];
  const seen = new Set<string>();
  const teams: CoachTeam[] = [];
  let i = 0;
  for (const r of rows) {
    const t = (r as any).teams as { id: string; name: string; club_id: string; clubs?: { name: string } } | null;
    if (!t || seen.has(t.id)) continue;
    seen.add(t.id);
    teams.push({
      id: t.id,
      clubId: t.club_id,
      name: t.name,
      clubName: t.clubs?.name ?? '',
      label: t.clubs?.name ? `${t.clubs.name} · ${t.name}` : t.name,
      color: TEAM_COLORS[i % TEAM_COLORS.length],
    });
    i += 1;
  }
  return teams;
}

export async function getMyProfile(personId: string): Promise<{ name: string; initials: string }> {
  const { data, error } = await supabase.from('users').select('first_name, last_name').eq('id', personId).single();
  if (error) throw error;
  const first = data?.first_name ?? '';
  const last = data?.last_name ?? '';
  const name = [first, last].filter(Boolean).join(' ') || 'Coach';
  const initials = `${first[0] ?? ''}${last[0] ?? ''}`.toUpperCase() || '?';
  return { name, initials };
}

