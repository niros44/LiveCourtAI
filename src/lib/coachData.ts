/** No unique constraint backs this table, so this looks up any existing row for
 * (coach, player, event) first and updates it — otherwise inserts a new one. */
export async function saveFeedback(
  existingId: string | null,
  input: { coachId: string; playerId: string; teamId: string; eventId: string; note: string; feedbackTypeId: number | null }
): Promise<string> {
  if (existingId) {
    const { error } = await supabase
      .from('player_feedback')
      .update({ note: input.note, feedback_type_id: input.feedbackTypeId })
      .eq('id', existingId);
    if (error) throw error;
    return existingId;
  }

  const { data, error } = await supabase
    .from('player_feedback')
    .insert({
      coach_id: input.coachId,
      player_id: input.playerId,
      team_id: input.teamId,
      event_id: input.eventId,
      note: input.note,
      feedback_type_id: input.feedbackTypeId,
    })
    .select('id')
    .single();
  if (error) throw error;
  return data.id as string;
}

