export type CoachEvent = {
  id: string;
  teamId: string;
  type: string; // 'practice' | 'game'
  title: string;
  eventStatus: string; // 'scheduled' | 'completed' | 'cancelled'
  startsAt: string;
  endsAt: string;
  facilityId: string | null;
  facilityName: string | null;
  opponentName: string | null;
  isHomeGame: boolean | null;
  confirmed: number;
  declined: number;
  pending: number;
  roster: number;
};

async function withRsvpCounts(events: any[], rosterByTeam: Map<string, RosterPlayer[]>): Promise<CoachEvent[]> {
  const eventIds = events.map((e) => e.id as string);
  const { data: responseRows } = eventIds.length
    ? await supabase.from('event_responses').select('event_id, player_id, status').in('event_id', eventIds)
    : { data: [] as any[] };

  const byEvent = new Map<string, { attending: number; declined: number; responded: Set<string> }>();
  for (const r of responseRows ?? []) {
    const key = r.event_id as string;
    const bucket = byEvent.get(key) ?? { attending: 0, declined: 0, responded: new Set<string>() };
    bucket.responded.add(r.player_id as string);
    if (r.status === 'attending') bucket.attending += 1;
    if (r.status === 'not_attending') bucket.declined += 1;
    byEvent.set(key, bucket);
  }

  return events.map((e) => {
    const roster = rosterByTeam.get(e.team_id as string) ?? [];
    const bucket = byEvent.get(e.id as string);
    const confirmed = bucket?.attending ?? 0;
    const declined = bucket?.declined ?? 0;
    return {
      id: e.id as string,
      teamId: e.team_id as string,
      type: e.type as string,
      title: e.title as string,
      eventStatus: e.status as string,
      startsAt: e.starts_at as string,
      endsAt: e.ends_at as string,
      facilityId: (e.facility_id as string | null) ?? null,
      facilityName: (e as any).facilities?.name ?? null,
      opponentName: (e.opponent_name as string | null) ?? null,
      isHomeGame: (e.is_home_game as boolean | null) ?? null,
      confirmed,
      declined,
      pending: Math.max(roster.length - confirmed - declined, 0),
      roster: roster.length,
    };
  });
}

export async function getTeamsEvents(
  teams: CoachTeam[],
  range: { from: Date; to: Date },
  roster?: RosterPlayer[]
): Promise<CoachEvent[]> {
  const teamIds = teams.map((t) => t.id);
  if (!teamIds.length) return [];

  const { data: eventRows, error } = await supabase
    .from('events')
    .select('id, team_id, type, title, starts_at, ends_at, status, opponent_name, is_home_game, facility_id, facilities ( name )')
    .in('team_id', teamIds)
    .eq('is_active', true)
    .gte('starts_at', range.from.toISOString())
    .lte('starts_at', range.to.toISOString())
    .order('starts_at', { ascending: true });
  if (error) throw error;

  const rosterList = roster ?? (await getRosters(teamIds));
  const rosterByTeam = new Map<string, RosterPlayer[]>();
  for (const p of rosterList) {
    const list = rosterByTeam.get(p.teamId) ?? [];
    list.push(p);
    rosterByTeam.set(p.teamId, list);
  }

  return withRsvpCounts(eventRows ?? [], rosterByTeam);
}

/** The next scheduled (future, not cancelled) event for one team, or null. */
export async function getNextEventForTeam(teamId: string, roster: RosterPlayer[]): Promise<CoachEvent | null> {
  const { data, error } = await supabase
    .from('events')
    .select('id, team_id, type, title, starts_at, ends_at, status, opponent_name, is_home_game, facility_id, facilities ( name )')
    .eq('team_id', teamId)
    .eq('is_active', true)
    .eq('status', 'scheduled')
    .gte('starts_at', new Date().toISOString())
    .order('starts_at', { ascending: true })
    .limit(1);
  if (error) throw error;
  if (!data?.length) return null;

  const rosterByTeam = new Map([[teamId, roster.filter((p) => p.teamId === teamId)]]);
  const [event] = await withRsvpCounts(data, rosterByTeam);
  return event;
}

