/**
 * Coach-facing data access, backed by real Supabase tables (no mock data).
 *
 * Access chain (verified against live RLS policies):
 *  - team_coaches.user_id = me, is_active  -> which teams I coach
 *  - events.team_id in (my teams)          -> my teams' schedule
 *  - event_responses / team_members        -> RSVP roll-up per event
 *  - player_feedback (coach_id = me)       -> my notes on a player for an event
 *  - player_measurements (is_current)      -> latest height/weight/wingspan
 *  - games_live_session / game_events_log  -> box-score source (no in-app
 *    recorder exists yet anywhere in this app, mockup included, so these
 *    almost always resolve to empty results today — the queries are real,
 *    the data just hasn't been generated by anything yet)
 *  - playbooks / plays (canvas_data jsonb) -> saved drill diagrams
 *
 * There is no "events DELETE" RLS policy (by design — nothing may hard
 * delete a scheduled event), so "delete" here means `is_active = false`,
 * and every read filters `is_active = true` explicitly.
 */

const TEAM_COLORS = [colors.navy, colors.buzzer, colors.purple, colors.blue, colors.green, colors.gold];

